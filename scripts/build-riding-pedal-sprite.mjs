/**
 * `public/riding/0512(N).png` 또는 `0512 (N).png` 시퀀스를 가로 스프라이트로 합친다.
 * 출력: `public/riding/pedal-sprite.png` (전체 RGBA 투명 배경)
 * 동기: `ridingPedalSpriteMeta.generated.ts` — App 이 프레임 수·셀 크기를 가져간다.
 */
import fs from 'fs';
import sharp from 'sharp';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const RIDING_DIR = join(root, 'public', 'riding');
const OUT = join(RIDING_DIR, 'pedal-sprite.png');
const META_OUT = join(root, 'ridingPedalSpriteMeta.generated.ts');

/** App.tsx `SIMULATION_MARKER_SIZE_PX` 와 동기 */
const CELL = 120;
/** 가장자리와 이어진 “거의 흰색” 배경만 투명 처리 (RGB 모두 ≥ 이 값) */
const EDGE_WHITE_THRESHOLD = Number(process.env.RIDING_EDGE_WHITE_THRESHOLD ?? 249);

/** `0512(10).png` / `0512 (100).png` 등 */
const FRAME_RE = /^0512\s*\((\d+)\)\.png$/i;

/**
 * 테두리에서만 BFS — 캐릭터 내부의 밝은색(흰색 디테일)은 가장자리와 안 이어지면 유지.
 */
function applyEdgeConnectedNearWhiteToTransparent(data, width, height, thr) {
  const nearWhite = (di) => {
    const r = data[di];
    const g = data[di + 1];
    const b = data[di + 2];
    return r >= thr && g >= thr && b >= thr;
  };
  const visited = new Uint8Array(width * height);
  const q = [];
  const tryPush = (x, y) => {
    if (x < 0 || x >= width || y < 0 || y >= height) return;
    const idx = y * width + x;
    if (visited[idx]) return;
    const di = idx * 4;
    if (!nearWhite(di)) return;
    visited[idx] = 1;
    q.push(idx);
  };
  for (let x = 0; x < width; x++) {
    tryPush(x, 0);
    tryPush(x, height - 1);
  }
  for (let y = 0; y < height; y++) {
    tryPush(0, y);
    tryPush(width - 1, y);
  }
  for (let qi = 0; qi < q.length; qi++) {
    const idx = q[qi];
    const x = idx % width;
    const y = (idx / width) | 0;
    tryPush(x + 1, y);
    tryPush(x - 1, y);
    tryPush(x, y + 1);
    tryPush(x, y - 1);
  }
  for (let i = 0; i < visited.length; i++) {
    if (!visited[i]) continue;
    const di = i * 4;
    data[di] = 0;
    data[di + 1] = 0;
    data[di + 2] = 0;
    data[di + 3] = 0;
  }
}

function listFrameFiles() {
  return fs
    .readdirSync(RIDING_DIR)
    .filter((f) => FRAME_RE.test(f))
    .filter((f) => f.toLowerCase() !== 'pedal-sprite.png')
    .sort((a, b) => {
      const na = parseInt(a.match(FRAME_RE)[1], 10);
      const nb = parseInt(b.match(FRAME_RE)[1], 10);
      return na - nb;
    });
}

async function main() {
  if (!fs.existsSync(RIDING_DIR)) {
    throw new Error(`Missing directory: ${RIDING_DIR}`);
  }

  const names = listFrameFiles();
  if (names.length === 0) {
    throw new Error(`No frames matching 0512(N).png or 0512 (N).png in ${RIDING_DIR}`);
  }

  const frameBuffers = [];
  for (const name of names) {
    const p = join(RIDING_DIR, name);
    const meta = await sharp(p).metadata();
    if (!meta.hasAlpha) {
      console.warn(`[riding-sprite] no alpha channel (export RGBA if you need transparency): ${name}`);
    }
    const { data, info } = await sharp(p).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
    if (info.channels !== 4) {
      throw new Error(`[riding-sprite] expected RGBA for ${name}, got channels=${info.channels}`);
    }
    const rgba = Buffer.from(data);
    applyEdgeConnectedNearWhiteToTransparent(rgba, info.width, info.height, EDGE_WHITE_THRESHOLD);
    const buf = await sharp(rgba, {
      raw: { width: info.width, height: info.height, channels: 4 },
    })
      .ensureAlpha()
      .resize(CELL, CELL, {
        fit: 'contain',
        background: { r: 0, g: 0, b: 0, alpha: 0 },
      })
      .png({ compressionLevel: 9, adaptiveFiltering: true })
      .toBuffer();
    frameBuffers.push(buf);
  }

  const n = frameBuffers.length;
  await sharp({
    create: {
      width: CELL * n,
      height: CELL,
      channels: 4,
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    },
  })
    .composite(frameBuffers.map((buf, i) => ({ input: buf, left: i * CELL, top: 0 })))
    .png({ compressionLevel: 9, adaptiveFiltering: true })
    .toFile(OUT);

  const metaTs =
    '/**\n' +
    ' * Generated by `npm run build:riding-sprite` — do not edit by hand.\n' +
    ' */\n' +
    `export const RIDING_PEDAL_FRAME_COUNT = ${n} as const;\n` +
    `export const RIDING_PEDAL_CELL_PX = ${CELL} as const;\n`;
  fs.writeFileSync(META_OUT, metaTs, 'utf8');

  console.log('Wrote', OUT, { frames: n, width: CELL * n, height: CELL });
  console.log('Wrote', META_OUT);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
